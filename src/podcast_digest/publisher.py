def to_whisper_json(pub: PublisherTranscript) -> str:
    """The whisper.cpp JSON shape the pipeline reads back on resume, plus the
    source, so a later tick knows the transcript came from the publisher."""
    return json.dumps({
        "source": {"kind": "publisher", "url": pub.link.url, "type": pub.link.type},
        "transcription": [
            {"offsets": {"from": int(s.start * 1000), "to": int(s.end * 1000)}, "text": s.text}
            for s in pub.transcript.segments
        ],
    }, ensure_ascii=False)


def to_markdown(pub: PublisherTranscript, *, title: str, show: str) -> str:
    """A readable Markdown transcript (the `cleaned` attachment) straight from
    the publisher's text: speaker turns with timestamps, no LLM pass."""
    lines = [f"# {title}", "", f"_{show}_ — transcript from the publisher", ""]
    if not pub.transcript.segments:
        lines.append(pub.transcript.text)
    for seg in pub.transcript.segments:
        h, rem = divmod(int(seg.start), 3600)
        m, s = divmod(rem, 60)
        text = seg.text
        if seg.speaker and text.startswith(f"{seg.speaker}: "):
            text = f"**{seg.speaker}:** {text[len(seg.speaker) + 2:]}"
        lines.append(f"[{h:02d}:{m:02d}:{s:02d}] {text}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def source_of(segments_json_path) -> str:
    """"publisher" or "whisper", from a transcript JSON artifact."""
    try:
        data = json.loads(segments_json_path.read_text(encoding="utf-8"))
    except (OSError, ValueError, AttributeError):
        return "whisper"
    source = data.get("source") if isinstance(data, dict) else None
    return "publisher" if isinstance(source, dict) and source.get("kind") == "publisher" else "whisper"
