"""Publisher transcripts (Podcasting 2.0 ``<podcast:transcript>``).

Many podcast feeds link a transcript per episode, written or generated by the
publisher. When one is usable it replaces download + local transcription:
faster, cheaper, and often better (punctuation, speaker names).

    <podcast:transcript url="https://cdn.example.com/ep.vtt" type="text/vtt" language="en"/>

An item may list several formats. We prefer timed ones — the JSON transcript
format, then WebVTT, then SubRip — over HTML and plain text, and the feed's
language over others. A transcript is only used when it is plausible for the
episode (enough words for the declared duration, timing that covers most of
it); otherwise the next candidate is tried, and if none fits the pipeline falls
back to whisper. Feeds, URLs and transcript bodies are untrusted: fetches go
through the same outbound-URL guard as audio, with a size cap.

Spec: https://github.com/Podcastindex-org/podcast-namespace (transcript tag
and transcripts.md).
"""
from __future__ import annotations

import html
import json
import logging
import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from io import BytesIO

import httpx

from .log import err_fields, event
from .transcribe import Segment, Transcript

logger = logging.getLogger(__name__)

# The namespace has been published under both schemes, with and without a
# trailing slash; match on the stable part.
_NAMESPACE_MARK = "podcastindex.org/namespace"
MAX_TRANSCRIPT_BYTES = 10 * 1024 * 1024
# Normal speech runs ~130-170 words per minute. A transcript with far fewer
# words than the episode is long is a teaser, a partial or a chapter list.
MIN_WORDS_PER_MINUTE = 40
MIN_WORDS = 100
# Timed transcripts must reach at least this share of the declared duration.
MIN_COVERAGE = 0.6


@dataclass(frozen=True)
class TranscriptLink:
    url: str
    type: str
    language: str | None = None
    rel: str | None = None


@dataclass(frozen=True)
class PublisherTranscript:
    transcript: Transcript
    link: TranscriptLink

    @property
    def end_seconds(self) -> float | None:
        segs = self.transcript.segments
        return max(s.end for s in segs) if segs else None


# ---------------------------------------------------------------------------
# Discovery: the tags of every item
# ---------------------------------------------------------------------------


def _local(tag: str) -> tuple[str, str]:
    """('{ns}name') → (ns, name)."""
    if tag.startswith("{"):
        ns, _, name = tag[1:].partition("}")
        return ns, name
    return "", tag


def transcript_links(rss_body: bytes) -> dict[str, tuple[TranscriptLink, ...]]:
    """Map each item's GUID (and its position, as ``#<index>``) to its
    transcript links. Never raises: a feed this parser cannot read simply has
    no publisher transcripts (feedparser parses the rest more leniently)."""
    links: dict[str, tuple[TranscriptLink, ...]] = {}
    index = 0
    try:
        for _event, elem in ET.iterparse(BytesIO(rss_body), events=("end",)):
            _ns, name = _local(elem.tag)
            if name not in ("item", "entry"):
                continue
            guid = ""
            found: list[TranscriptLink] = []
            for child in elem:
                cns, cname = _local(child.tag)
                if cname in ("guid", "id") and not guid:
                    guid = (child.text or "").strip()
                elif cname == "transcript" and _NAMESPACE_MARK in cns:
                    url = (child.get("url") or "").strip()
                    if url:
                        found.append(TranscriptLink(
                            url=url,
                            type=(child.get("type") or "").strip().lower(),
                            language=(child.get("language") or "").strip().lower() or None,
                            rel=(child.get("rel") or "").strip().lower() or None,
                        ))
            if found:
                if guid:
                    links[guid] = tuple(found)
                links[f"#{index}"] = tuple(found)
            index += 1
            elem.clear()
    except ET.ParseError as e:
        logger.debug("publisher.feed_unparseable err=%s", e)
    return links


# ---------------------------------------------------------------------------
# Choosing a format
# ---------------------------------------------------------------------------

_FORMAT_RANK = {"json": 0, "vtt": 1, "srt": 2, "html": 3, "text": 4}


def _format(link: TranscriptLink) -> str | None:
    t = link.type
    path = link.url.split("?", 1)[0].lower()
    if "json" in t or (not t and path.endswith(".json")):
        return "json"
    if "vtt" in t or (not t and path.endswith(".vtt")):
        return "vtt"
    if "subrip" in t or "srt" in t or (not t and path.endswith(".srt")):
        return "srt"
    if "html" in t or (not t and path.endswith((".html", ".htm"))):
        return "html"
    if t.startswith("text/plain") or (not t and path.endswith(".txt")):
        return "text"
    return None


def candidates(
    links: tuple[TranscriptLink, ...], *, language: str | None,
) -> list[tuple[TranscriptLink, str]]:
    """Usable links in preference order: the feed's language (English when
    unset) first, then timed formats before untimed ones."""
    want = (language or "en").split("-", 1)[0]

    def lang_rank(link: TranscriptLink) -> int:
        if not link.language:
            return 1
        return 0 if link.language.split("-", 1)[0] == want else 2

    usable = [(link, fmt) for link in links if (fmt := _format(link))]
    usable.sort(key=lambda lf: (lang_rank(lf[0]), _FORMAT_RANK[lf[1]]))
    return usable


# ---------------------------------------------------------------------------
# Parsers
# ---------------------------------------------------------------------------

_TS_RE = re.compile(r"(?:(\d+):)?(\d{1,2}):(\d{2})(?:[.,](\d{1,3}))?")
_CUE_TIMING_RE = re.compile(
    r"^\s*(\S+)\s*-->\s*(\S+)",
)
_VOICE_RE = re.compile(r"<v(?:\.[^\s>]*)?\s+([^>]+)>", re.IGNORECASE)
_TAG_RE = re.compile(r"<[^>]+>")


def _seconds(ts: str) -> float | None:
    m = _TS_RE.fullmatch(ts.strip())
    if not m:
        return None
    h, mnt, s, frac = m.groups()
    total = float(int(h or 0) * 3600 + int(mnt) * 60 + int(s))
    if frac:
        total += int(frac.ljust(3, "0")) / 1000
    return total


def _clean_text(s: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(_TAG_RE.sub("", s))).strip()


def _parse_cues(text: str) -> list[Segment]:
    """WebVTT and SubRip share the cue shape: timing line, then payload."""
    segments: list[Segment] = []
    blocks = re.split(r"\r?\n\s*\r?\n", text.replace("﻿", ""))
    for block in blocks:
        lines = [ln for ln in block.splitlines() if ln.strip()]
        timing_at = next((i for i, ln in enumerate(lines) if "-->" in ln), None)
        if timing_at is None:
            continue  # header, NOTE, STYLE, REGION
        m = _CUE_TIMING_RE.match(lines[timing_at])
        if not m:
            continue
        start, end = _seconds(m.group(1)), _seconds(m.group(2))
        if start is None or end is None:
            continue
        payload = " ".join(lines[timing_at + 1:])
        voice = _VOICE_RE.search(payload)
        speaker = voice.group(1).strip() if voice else None
        body = _clean_text(payload)
        if body:
            segments.append(Segment(start=start, end=max(start, end), text=body, speaker=speaker))
    return segments


def _parse_json(text: str) -> list[Segment]:
    data = json.loads(text)
    raw = data.get("segments") if isinstance(data, dict) else None
    segments: list[Segment] = []
    for seg in raw or []:
        if not isinstance(seg, dict):
            continue
        body = _clean_text(str(seg.get("body") or ""))
        try:
            start = float(seg["startTime"])
            end = float(seg.get("endTime", start))
        except (KeyError, TypeError, ValueError):
            continue
        if body:
            speaker = str(seg.get("speaker") or "").strip() or None
            segments.append(Segment(start=start, end=max(start, end), text=body, speaker=speaker))
    return segments


_BLOCK_RE = re.compile(r"</?(p|div|br|li|h\d|cite|time)[^>]*>", re.IGNORECASE)


def _html_to_text(text: str) -> str:
    text = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", text, flags=re.DOTALL | re.IGNORECASE)
    text = _BLOCK_RE.sub("\n", text)
    lines = [_clean_text(ln) for ln in text.splitlines()]
    return "\n".join(ln for ln in lines if ln)


def _merge(segments: list[Segment], *, max_chars: int = 400, max_gap: float = 2.0) -> list[Segment]:
    """Join word- or caption-sized pieces into readable turns: consecutive
    pieces of the same speaker, close in time, up to ``max_chars``. Drops
    immediate repeats (rolling captions)."""
    merged: list[Segment] = []
    for seg in sorted(segments, key=lambda s: s.start):
        if merged:
            last = merged[-1]
            if seg.text == last.text:
                continue
            same_turn = seg.speaker == last.speaker and seg.start - last.end <= max_gap
            if same_turn and len(last.text) + len(seg.text) < max_chars:
                merged[-1] = Segment(
                    start=last.start, end=max(last.end, seg.end),
                    text=f"{last.text} {seg.text}", speaker=last.speaker,
                )
                continue
        merged.append(seg)
    return merged


def _with_speakers(segments: list[Segment]) -> list[Segment]:
    """Fold speaker names into the text at each change of speaker, so every
    consumer (summary, cleanup, webhook) sees who is talking."""
    out: list[Segment] = []
    previous: str | None = None
    for seg in segments:
        text = seg.text
        if seg.speaker and seg.speaker != previous:
            text = f"{seg.speaker}: {text}"
        previous = seg.speaker or previous
        out.append(Segment(start=seg.start, end=seg.end, text=text, speaker=seg.speaker))
    return out


def parse(body: str, fmt: str) -> Transcript:
    """Parse a transcript body of the given format. Raises ValueError when it
    holds no text."""
    if fmt in ("vtt", "srt"):
        segments = _with_speakers(_merge(_parse_cues(body)))
    elif fmt == "json":
        segments = _with_speakers(_merge(_parse_json(body)))
    else:
        text = _html_to_text(body) if fmt == "html" else body.strip()
        if not text:
            raise ValueError("empty transcript")
        return Transcript(text=text, segments=[])
    if not segments:
        raise ValueError("no timed text in transcript")
    return Transcript(text=" ".join(s.text for s in segments), segments=segments)


def implausible(transcript: Transcript, *, declared_seconds: int | None) -> str | None:
    """Why this transcript cannot stand in for the episode, or None."""
    words = len(transcript.text.split())
    minutes = (declared_seconds or 0) / 60
    floor = max(MIN_WORDS, int(minutes * MIN_WORDS_PER_MINUTE))
    if words < floor:
        return f"{words} words, expected at least {floor}"
    if declared_seconds and transcript.segments:
        covered = max(s.end for s in transcript.segments)
        if covered < declared_seconds * MIN_COVERAGE:
            return f"covers {covered:.0f}s of {declared_seconds}s"
    return None


# ---------------------------------------------------------------------------
# Fetch
# ---------------------------------------------------------------------------


async def _get(url: str, *, client: httpx.AsyncClient) -> str:
    async with client.stream("GET", url) as resp:
        resp.raise_for_status()
        chunks: list[bytes] = []
        size = 0
        async for chunk in resp.aiter_bytes():
            size += len(chunk)
            if size > MAX_TRANSCRIPT_BYTES:
                raise ValueError(f"transcript larger than {MAX_TRANSCRIPT_BYTES} bytes")
            chunks.append(chunk)
        raw = b"".join(chunks)
        return raw.decode(resp.encoding or "utf-8", errors="replace")


async def fetch(
    links: tuple[TranscriptLink, ...],
    *,
    client: httpx.AsyncClient,
    language: str | None,
    declared_seconds: int | None,
    guid: str | None = None,
) -> PublisherTranscript | None:
    """The first usable, plausible publisher transcript, or None (the caller
    then transcribes the audio). Never raises."""
    for link, fmt in candidates(links, language=language):
        try:
            body = await _get(link.url, client=client)
            transcript = parse(body, fmt)
        except Exception as e:  # noqa: BLE001 - any failure → next candidate
            event(logger, logging.INFO, "publisher.transcript_unusable",
                  guid=guid, url=link.url, format=fmt, **err_fields(e))
            continue
        problem = implausible(transcript, declared_seconds=declared_seconds)
        if problem:
            event(logger, logging.INFO, "publisher.transcript_implausible",
                  guid=guid, url=link.url, format=fmt, problem=problem)
            continue
        event(logger, logging.INFO, "publisher.transcript_used",
              guid=guid, url=link.url, format=fmt,
              words=len(transcript.text.split()), segments=len(transcript.segments))
        return PublisherTranscript(transcript=transcript, link=link)
    return None


