async def test_summary_stored_before_upgrade_is_not_relabeled(
    settings, db, feeds_file, mock_llm, mock_transcribe, mock_http, monkeypatch,
):
    monkeypatch.setattr(pipeline, "BUILD", BUILD_A, raising=False)
    # A genuinely old summarized row has no delivery envelope yet. Creating a
    # failed new-version delivery here would freeze its original footer.
    await run_tick(settings=settings, feeds_file=feeds_file,
                   db=db, mailer=None, dry_run=True)
    db.close()
    with sqlite3.connect(settings.db_path) as old:
        old.execute("ALTER TABLE episodes DROP COLUMN summary_build")
    old.close()

    upgraded = Database(settings.db_path)
    try:
        legacy = upgraded.get_episode(FEED_URL, GUID)
        assert legacy.status == "summarized" and legacy.summary_html
        assert legacy.summary_build is None

        monkeypatch.setattr(pipeline, "BUILD", BUILD_B, raising=False)
        mailer = FakeMailer()
        stats = await run_tick(settings=settings, feeds_file=feeds_file,
                               db=upgraded, mailer=mailer, dry_run=False)

        assert stats["emailed"] == 1
        assert len(mock_llm.calls) == 1
        [sent] = mailer.sent
        assert "Test summary of 'Episode 3: Long episode'" in sent["body_html"]
        assert "Generated by" not in sent["body_html"]
        delivered = upgraded.get_episode(FEED_URL, GUID)
        assert delivered.status == "emailed" and delivered.summary_build is None
    finally:
        upgraded.close()


def test_summary_provenance_follows_its_summary(db):
    db.insert_episode(feed_url=FEED_URL, guid=GUID, title="Episode 3",
                      published_at="2026-06-01T00:00:00+00:00", duration_seconds=5400,
                      audio_url="https://cdn.example.com/ep3.mp3")
    db.set_status(feed_url=FEED_URL, guid=GUID, status="summarized",
                  summary_html="<p>first</p>", summary_build=BUILD_A)
    assert db.get_episode(FEED_URL, GUID).summary_build == BUILD_A

    db.set_status(feed_url=FEED_URL, guid=GUID, status="summarized",
                  summary_html="<p>second</p>")
    replaced = db.get_episode(FEED_URL, GUID)
    assert (replaced.summary_html, replaced.summary_build) == ("<p>second</p>", None)

    with pytest.raises(ValueError, match="summary_build requires summary_html"):
        db.set_status(feed_url=FEED_URL, guid=GUID, status="summarized",
                      summary_build=BUILD_B)
    assert db.get_episode(FEED_URL, GUID).summary_build is None


def test_old_schema_migration_only_adds_nullable_summary_build(tmp_path):
    path = tmp_path / "legacy.sqlite"
    with sqlite3.connect(path) as old:
        old.executescript(SCHEMA.replace("    summary_build TEXT,\n", ""))
        old.execute("PRAGMA user_version = 1")
        old.executemany(
            """INSERT INTO episodes
            (feed_url, guid, title, published_at, audio_url, summary_html,
             status, terminal_reason, attempts, emailed_at, wiki_pushed_at,
             created_at, updated_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            [
                (FEED_URL, "legacy-pending", "Synthetic pending", "2026-06-01",
                 "https://cdn.example.com/pending.mp3", "<p>Pending summary</p>",
                 "summarized", None, 2, None, None, "2026-06-01", "2026-06-01"),
                (FEED_URL, "legacy-sent", "Synthetic sent", "2026-06-02",
                 "https://cdn.example.com/sent.mp3", "<p>Sent summary</p>",
                 "emailed", "sent", 0, "2026-06-02T01:00:00Z", "2026-06-02T02:00:00Z",
                 "2026-06-02", "2026-06-02"),
            ],
        )
        old.execute("INSERT INTO meta VALUES ('synthetic-watermark', 'keep')")
        before_columns = [row[1] for row in old.execute("PRAGMA table_info(episodes)")]
        before_rows = old.execute("SELECT * FROM episodes ORDER BY guid").fetchall()
        before_indexes = old.execute("SELECT name, sql FROM sqlite_master WHERE type='index'").fetchall()
    for _ in range(2):
        upgraded = Database(path)
        try:
            assert upgraded.get_episode(FEED_URL, "legacy-pending").summary_build is None
            assert upgraded.get_episode(FEED_URL, "legacy-sent").summary_build is None
        finally:
            upgraded.close()
        with sqlite3.connect(path) as after:
            columns = after.execute("PRAGMA table_info(episodes)").fetchall()
            assert [row[1] for row in columns] == [*before_columns, "summary_build"]
            assert columns[-1][2:5] == ("TEXT", 0, None)
            assert after.execute("SELECT summary_build FROM episodes").fetchall() == [(None,), (None,)]
            assert after.execute(
                f"SELECT {', '.join(before_columns)} FROM episodes ORDER BY guid"
            ).fetchall() == before_rows
            assert after.execute("SELECT * FROM meta").fetchall() == [("synthetic-watermark", "keep")]
            assert after.execute("PRAGMA user_version").fetchone() == (1,)
            assert after.execute(
                "SELECT name, sql FROM sqlite_master WHERE type='index'"
            ).fetchall() == before_indexes
            assert after.execute("PRAGMA integrity_check").fetchone() == ("ok",)
