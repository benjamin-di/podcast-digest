GUID = "ep-3-guid"
BUILD_A = BuildIdentity("podcast-digest", "0.4.7", "a" * 40)
BUILD_B = BuildIdentity("podcast-digest", "0.4.8", "b" * 64)
FOOTER_A = f"Generated by podcast-digest 0.4.7, source revision {'a' * 40}."


async def test_delivered_digest_names_the_composing_build(
    settings, db, feeds_file, mock_llm, mock_transcribe, mock_http, monkeypatch,
):
    monkeypatch.setattr(pipeline, "BUILD", BUILD_A, raising=False)
    server = _Server()
    mailer = SmtpMailer(host="127.0.0.1", port=server.port,
                        sender="bot@example.com", security="none")

    stats = await run_tick(settings=settings, feeds_file=feeds_file,
                           db=db, mailer=mailer, dry_run=False)
    server.thread.join(timeout=5)

    assert stats["emailed"] == 1
    assert len(server.messages) == 1
    msg = email.message_from_bytes(server.messages[0], policy=policy.default)
    html = msg.get_body(preferencelist=("html",)).get_content()
    text = msg.get_body(preferencelist=("plain",)).get_content()
    assert html.count("Generated by") == 1 and FOOTER_A in html
    assert text.count("Generated by") == 1 and text.rstrip().endswith(FOOTER_A)
    assert "Test summary of 'Episode 3: Long episode'" in text

    ep = db.get_episode(FEED_URL, GUID)
    assert (ep.status, ep.terminal_reason) == ("emailed", "sent")
    assert ep.emailed_at is not None
    assert ep.summary_build == BUILD_A
    assert "Generated by" not in ep.summary_html


async def test_later_build_retrying_the_send_keeps_the_composing_build(
    settings, db, feeds_file, mock_llm, mock_transcribe, mock_http, monkeypatch,
    tmp_path,
):
    log_path = tmp_path / "emitted.tsv"
    settings.PODCAST_DIGEST_EMITTED_LOG = str(log_path)
    ingestor = FakeIngestor()
    monkeypatch.setattr(pipeline, "_build_webhook", lambda _settings: ingestor)

    monkeypatch.setattr(pipeline, "BUILD", BUILD_A, raising=False)
    failed = await run_tick(settings=settings, feeds_file=feeds_file,
                            db=db, mailer=FakeMailer(fail=True), dry_run=False)
    assert (failed["emailed"], failed["failed"]) == (0, 1)
    parked = db.get_episode(FEED_URL, GUID)
    assert (parked.status, parked.attempts, parked.emailed_at) == ("summarized", 1, None)
    assert parked.summary_build == BUILD_A
    assert not log_path.exists() or GUID not in log_path.read_text()
    assert ingestor.pushes == []

    monkeypatch.setattr(pipeline, "BUILD", BUILD_B, raising=False)
    mailer = FakeMailer()
    retried = await run_tick(settings=settings, feeds_file=feeds_file,
                             db=db, mailer=mailer, dry_run=False)

    assert retried["emailed"] == 1
    assert len(mock_llm.calls) == 1
    [sent] = mailer.sent
    assert sent["body_html"].count("Generated by") == 1 and FOOTER_A in sent["body_html"]
    assert "0.4.8" not in sent["body_html"] and "b" * 64 not in sent["body_html"]
    delivered = db.get_episode(FEED_URL, GUID)
    assert (delivered.status, delivered.terminal_reason) == ("emailed", "sent")
    assert delivered.summary_build == BUILD_A
    assert log_path.read_text().count(GUID) == 1
    [pushed] = ingestor.pushes
    assert "Generated by" not in pushed.summary

    again = FakeMailer()
    idle = await run_tick(settings=settings, feeds_file=feeds_file,
                          db=db, mailer=again, dry_run=False)
    assert idle["emailed"] == 0 and again.sent == []


